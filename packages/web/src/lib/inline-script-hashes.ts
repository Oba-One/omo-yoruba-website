/**
 * The hashes the Content Security Policy allows inline scripts by (ADR 0062). Every inline script the site
 * ships is a component's `<script is:inline>` (ADR 0018), and Astro ships its body exactly as the source
 * writes it, so the hashes come from the source. Every page's policy carries all of them, since the
 * ClientRouter runs the next page's scripts under the policy of the page it swapped from. Used by the
 * generator (`bun run csp:hashes`) and the test that keeps `csp-hashes.ts` current; never by a page.
 */
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync } from 'node:fs';
import { join, relative } from 'node:path';

/** The packages whose `.astro` components can reach a page. */
export const COMPONENT_DIRS = ['packages/ui/src', 'packages/web/src'] as const;

// An HTML comment, or a script element with its attributes and body. Scanned in one pass from the left, so a
// `<script>` written inside a comment is skipped and a `<!--` inside a script's body stays part of the body.
const COMMENT_OR_SCRIPT = /<!--[\s\S]*?-->|<script\b([^>]*?)(?:\/>|>([\s\S]*?)<\/script>)/g;
// A type the browser never runs as script, such as JSON-LD; the policy does not govern it.
const DATA_TYPE = /^type=["'](?!module|text\/javascript|application\/javascript)[^"']+["']$/;

/**
 * The body of every `<script is:inline>` in a component's template, skipping its frontmatter and comments.
 * Astro bundles a `<script>` with no attribute, or only `src`, into a file under /_astro; it ships any other
 * script inline (docs.astro.build, scripts). So a script with any attribute but `is:inline`, a data type
 * aside, throws: `define:vars` or `set:html` change its body per render, and the rest are kept to one form.
 */
export function inlineScriptBodies(source: string, file = 'a component'): string[] {
  const template = source.replace(/^---\r?\n[\s\S]*?\r?\n---(\r?\n|$)/, '');
  const bodies: string[] = [];
  for (const match of template.matchAll(COMMENT_OR_SCRIPT)) {
    if (match[0].startsWith('<!--')) continue;
    const attributes = (match[1] ?? '').trim();
    if (attributes === '' || /^src=\S+$/.test(attributes) || DATA_TYPE.test(attributes)) continue;
    if (attributes !== 'is:inline') {
      throw new Error(
        `${file}: <script ${attributes}> ships inline with a body no hash fixed at build can be sure of; write it as <script is:inline> or <script> (ADR 0062).`,
      );
    }
    bodies.push(match[2] ?? '');
  }
  return bodies;
}

/** A CSP hash source without its quotes, as `script-src` lists it. */
export function scriptHash(body: string): string {
  return `sha256-${createHash('sha256').update(body, 'utf8').digest('base64')}`;
}

/** Every inline script's hash under the repository root, sorted, with the components that ship it. */
export function componentScriptHashes(root: string): { hash: string; files: string[] }[] {
  const byHash = new Map<string, string[]>();
  for (const dir of COMPONENT_DIRS) {
    const entries = readdirSync(join(root, dir), { recursive: true, encoding: 'utf8' });
    for (const entry of entries.filter((name) => name.endsWith('.astro')).sort()) {
      const file = relative(root, join(root, dir, entry));
      for (const body of inlineScriptBodies(readFileSync(join(root, file), 'utf8'), file)) {
        const hash = scriptHash(body);
        byHash.set(hash, [...(byHash.get(hash) ?? []), file]);
      }
    }
  }
  return [...byHash]
    .map(([hash, files]) => ({ hash, files }))
    .sort((a, b) => (a.hash < b.hash ? -1 : 1));
}

/** The source of `csp-hashes.ts` for those hashes. */
export function hashesModule(
  entries: readonly { hash: string; files: readonly string[] }[],
): string {
  const lines = entries.flatMap(({ hash, files }) => [`  // ${files.join(', ')}`, `  '${hash}',`]);
  return [
    '// Generated by `bun run csp:hashes` from every `<script is:inline>` in packages/ui/src and packages/web/src',
    '// (src/lib/inline-script-hashes.ts, ADR 0062). Do not edit: change the component, then run the generator.',
    'export const INLINE_SCRIPT_HASHES: readonly string[] = [',
    ...lines,
    '];',
    '',
  ].join('\n');
}
